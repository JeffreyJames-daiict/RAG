"""Data models and execution state schemas for agentic RAG orchestration."""

from __future__ import annotations

import time
import uuid
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ExecutionStatus(str, Enum):
    """Overall lifecycle status of an agentic RAG run."""

    PENDING = "pending"
    PLANNING = "planning"
    EXECUTING = "executing"
    EVALUATING = "evaluating"
    REFINING = "refining"
    COMPLETED = "completed"
    PARTIAL = "partial"
    FAILED = "failed"
    CANCELLED = "cancelled"
    BUDGET_EXHAUSTED = "budget_exhausted"


class PlanStepStatus(str, Enum):
    """Execution status of an individual plan step."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    SKIPPED = "skipped"


class PlanStep(BaseModel):
    """A discrete planned step in an agentic workflow."""

    step_id: int = Field(..., description="1-based step order identifier")
    description: str = Field(..., description="Actionable description of the step")
    tool_name: str = Field(default="retriever", description="Target tool to invoke")
    tool_args: Dict[str, Any] = Field(default_factory=dict, description="Arguments for tool execution")
    status: PlanStepStatus = Field(default=PlanStepStatus.PENDING, description="Execution status of this step")
    result: Optional[Any] = Field(default=None, description="Output generated by step execution")
    error: Optional[str] = Field(default=None, description="Error message if step failed")


class ExecutionPlan(BaseModel):
    """Structured decomposition plan generated by PlannerAgent."""

    goal: str = Field(..., description="High-level goal or query to resolve")
    steps: List[PlanStep] = Field(default_factory=list, description="Ordered sequence of execution steps")
    is_simple: bool = Field(default=False, description="True if query requires only single-pass retrieval")


class RetrievedEvidence(BaseModel):
    """Standardized retrieved evidence chunk or snippet."""

    evidence_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8], description="Unique evidence ID")
    query: str = Field(..., description="Sub-query used to retrieve this evidence")
    snippet: str = Field(..., description="Retrieved textual or tabular content")
    chunk_id: Optional[str] = Field(default=None, description="Original chunk identifier")
    document_id: Optional[str] = Field(default=None, description="Source document identifier")
    score: float = Field(default=0.0, description="Retrieval or relevance score")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Source metadata")


class ToolCallRecord(BaseModel):
    """Audit record of an executed tool call."""

    call_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8], description="Unique call ID")
    tool_name: str = Field(..., description="Name of the invoked tool")
    inputs: Dict[str, Any] = Field(default_factory=dict, description="Serialized tool inputs")
    outputs: Optional[Any] = Field(default=None, description="Serialized tool outputs")
    success: bool = Field(default=True, description="Whether tool execution succeeded")
    error: Optional[str] = Field(default=None, description="Error message if execution failed")
    latency_ms: float = Field(default=0.0, description="Execution duration in milliseconds")


class Observation(BaseModel):
    """An observation recorded during the execution loop."""

    step: int = Field(..., description="Step index when observation was recorded")
    action: str = Field(..., description="Action that generated this observation")
    content: str = Field(..., description="Summarized observation content")
    timestamp: float = Field(default_factory=time.time, description="Unix timestamp")


class ExecutionBudget(BaseModel):
    """Resource budget and consumption tracker for an agentic run."""

    max_steps: int = Field(default=5, ge=1, description="Maximum execution loop steps allowed")
    max_retrievals: int = Field(default=4, ge=1, description="Maximum retrieval calls allowed")
    max_tools: int = Field(default=6, ge=0, description="Maximum auxiliary tool calls allowed")
    max_tokens: int = Field(default=4000, ge=100, description="Maximum LLM tokens allowed across all agents")
    max_cost: float = Field(default=0.05, ge=0.0, description="Maximum USD cost allowed")
    max_time_sec: float = Field(default=30.0, gt=0.0, description="Maximum wall-clock execution time in seconds")
    max_rewrites: int = Field(default=3, ge=0, description="Maximum query refinement iterations allowed")

    used_steps: int = Field(default=0)
    used_retrievals: int = Field(default=0)
    used_tools: int = Field(default=0)
    used_tokens: int = Field(default=0)
    used_cost: float = Field(default=0.0)
    elapsed_time_sec: float = Field(default=0.0)
    used_rewrites: int = Field(default=0)

    def can_step(self) -> bool:
        return self.used_steps < self.max_steps

    def can_retrieve(self) -> bool:
        return self.used_retrievals < self.max_retrievals

    def can_call_tool(self) -> bool:
        return self.used_tools < self.max_tools

    def can_consume_cost(self, additional_cost: float = 0.0) -> bool:
        return (self.used_cost + additional_cost) <= self.max_cost

    def can_rewrite(self) -> bool:
        return self.used_rewrites < self.max_rewrites

    def is_timed_out(self) -> bool:
        return self.elapsed_time_sec >= self.max_time_sec

    @property
    def remaining_steps(self) -> int:
        return max(0, self.max_steps - self.used_steps)

    @property
    def remaining_cost(self) -> float:
        return max(0.0, self.max_cost - self.used_cost)


class AgenticState(BaseModel):
    """Traceable, structured execution state for an agentic RAG run."""

    run_id: str = Field(default_factory=lambda: str(uuid.uuid4()), description="Unique run identifier")
    query: str = Field(..., description="Original user query")
    plan: Optional[ExecutionPlan] = Field(default=None, description="Decomposition execution plan")
    current_step: int = Field(default=0, description="Current step index")
    retrieved_evidence: List[RetrievedEvidence] = Field(default_factory=list, description="Accumulated evidence chunks")
    tool_results: List[ToolCallRecord] = Field(default_factory=list, description="History of executed tool calls")
    observations: List[Observation] = Field(default_factory=list, description="Timeline of agent observations")
    remaining_budget: ExecutionBudget = Field(default_factory=ExecutionBudget, description="Current resource budget")
    errors: List[str] = Field(default_factory=list, description="Logged warnings and non-fatal/fatal errors")
    final_answer: Optional[str] = Field(default=None, description="Synthesized final answer")
    status: ExecutionStatus = Field(default=ExecutionStatus.PENDING, description="Current run status")
    intermediate_trace: List[Dict[str, Any]] = Field(default_factory=list, description="Traceable audit log")

    def record_trace(self, event: str, payload: Dict[str, Any]) -> None:
        """Append an event to the intermediate trace audit log."""
        self.intermediate_trace.append({
            "timestamp": time.time(),
            "step": self.current_step,
            "status": self.status.value,
            "event": event,
            "payload": payload,
        })
