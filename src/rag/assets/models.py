"""Data transfer objects and models for visual asset and figure processing."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional, Tuple
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field
from rag.core.models import AssetType, DocumentAssetSchema, IndexingPolicy


class AssetLifecycleStatus(str, Enum):
    """Lifecycle status stages for visual assets."""
    PENDING = "PENDING"
    EXTRACTED = "EXTRACTED"
    HASHED = "HASHED"
    CLASSIFIED = "CLASSIFIED"
    OCR_PROCESSING = "OCR_PROCESSING"
    OCR_COMPLETED = "OCR_COMPLETED"
    VISION_PROCESSING = "VISION_PROCESSING"
    VISION_COMPLETED = "VISION_COMPLETED"
    READY = "READY"
    STORE_ONLY = "STORE_ONLY"
    SKIPPED = "SKIPPED"
    LOW_QUALITY = "LOW_QUALITY"
    FAILED = "FAILED"


@dataclass
class ExtractedVisualCandidate:
    """Raw candidate image extracted from PDF or scanned page before classification."""
    asset_id: str
    document_id: str
    version: int
    page_number: int
    bbox: Tuple[float, float, float, float]  # (x0, y0, x1, y1) in PDF points
    image_bytes: bytes
    mime_type: str = "image/png"
    width: int = 0
    height: int = 0
    source_type: str = "digital_embedded"  # "digital_embedded" | "scanned_crop"
    xref: Optional[int] = None
    nearby_text: Optional[str] = None
    section_heading: Optional[str] = None
    page_coverage: float = 0.0


@dataclass
class AssetContextInfo:
    """Surrounding document, section, and page textual context for an asset."""
    document_title: Optional[str] = None
    section_heading: Optional[str] = None
    subsection_heading: Optional[str] = None
    caption: Optional[str] = None
    nearby_text: Optional[str] = None
    ocr_text: Optional[str] = None


@dataclass
class AssetClassificationResult:
    """Evaluation result classifying the role and type of a visual candidate."""
    asset_type: AssetType = AssetType.FIGURE
    asset_subtype: Optional[str] = None
    confidence: float = 1.0
    is_decorative: bool = False
    reason: str = ""
    features: Dict[str, Any] = field(default_factory=dict)


@dataclass
class AssetRelevanceResult:
    """Result of cheap local heuristic relevance evaluation and policy selection."""
    relevance_score: float = 0.50
    relevance_reason: str = ""
    indexing_policy: IndexingPolicy = IndexingPolicy.STORE_ONLY
    features: Dict[str, Any] = field(default_factory=dict)


@dataclass
class FigureOCRResult:
    """Structured OCR extraction output from inside a figure."""
    ocr_text: str = ""
    confidence: float = 1.0
    words: List[str] = field(default_factory=list)
    tokens_count: int = 0
    ocr_applied: bool = False


class FigureEntityRelationship(BaseModel):
    """A directed semantic connection between entities in a diagram."""
    source: str = Field(description="Source entity/component name")
    relationship: str = Field(description="Directed action, predicate, or connector (e.g. sends_data_to, connects_to)")
    target: str = Field(description="Target entity/component name")


class StructuredVisionOutput(BaseModel):
    """Strictly validated structured response schema from vision models."""
    asset_type: AssetType = Field(default=AssetType.FIGURE, description="Classified visual asset type")
    asset_subtype: Optional[str] = Field(default=None, description="Domain-specific subtype (e.g. SYSTEM_ARCHITECTURE)")
    relevance_score: float = Field(default=0.90, ge=0.0, le=1.0, description="Model-evaluated document QA relevance score")
    relevance_reason: str = Field(default="", description="Justification for relevance and type")
    description: str = Field(default="", description="High-level narrative explaining what the figure depicts")
    visible_text_summary: Optional[str] = Field(default=None, description="Summary of text detected inside the figure")
    entities: List[str] = Field(default_factory=list, description="Key components, services, systems, or labels")
    relationships: List[FigureEntityRelationship] = Field(default_factory=list, description="Connections between components")
    technical_concepts: List[str] = Field(default_factory=list, description="Key technical or scientific concepts illustrated")
    summary: Optional[str] = Field(default="", description="One-line summary for rapid retrieval")

    model_config = ConfigDict(extra="ignore")


class FigureAnalysisResult(BaseModel):
    """Structured semantic analysis generated by a vision provider."""
    description: str = Field(default="", description="High-level narrative explaining what the figure/diagram depicts")
    entities: List[str] = Field(default_factory=list, description="Key components, systems, services, or labels detected")
    relationships: List[FigureEntityRelationship] = Field(default_factory=list, description="Connections between components")
    summary: str = Field(default="", description="One-line summary for rapid retrieval context")
    visible_text_summary: Optional[str] = Field(default=None, description="Summary of text detected inside the figure")
    technical_concepts: List[str] = Field(default_factory=list, description="Key technical concepts")
    provider_name: str = Field(default="mock", description="Vision provider model used")
    status: str = Field(default="SUCCESS", description="SUCCESS | FAILED | SKIPPED")
    error_message: Optional[str] = None
    raw_response: Optional[Dict[str, Any]] = None


@dataclass
class ProcessedAsset:
    """Fully analyzed and processed asset record ready for persistence and chunking."""
    schema: DocumentAssetSchema
    image_bytes: bytes
    classification: AssetClassificationResult
    relevance: Optional[AssetRelevanceResult] = None
    ocr_result: Optional[FigureOCRResult] = None
    analysis_result: Optional[FigureAnalysisResult] = None
    semantic_text_representation: str = ""


@dataclass
class AssetProcessingMetrics:
    """Operational observability metrics for visual asset processing."""
    total_extracted: int = 0
    stored_minio: int = 0
    duplicates_detected: int = 0
    ocr_processed: int = 0
    vision_analyzed: int = 0
    store_only: int = 0
    ignored: int = 0
    embedded_chunks: int = 0
    vision_failures: int = 0

    def to_dict(self) -> Dict[str, int]:
        return {
            "total_extracted": self.total_extracted,
            "stored_minio": self.stored_minio,
            "duplicates_detected": self.duplicates_detected,
            "ocr_processed": self.ocr_processed,
            "vision_analyzed": self.vision_analyzed,
            "store_only": self.store_only,
            "ignored": self.ignored,
            "embedded_chunks": self.embedded_chunks,
            "vision_failures": self.vision_failures,
        }
